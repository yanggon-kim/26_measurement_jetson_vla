"""T007 steps 3-5: results/<date>_E4g_c1_summary/ (c1_bounds.csv, c2_eager_vs_best.csv) and reports/E4g_c1_c2_bottlenecks.md
from the latest committed results/*_E4g_c1_<model>_<mode>/ncu/region_utilisation.csv (bench/t007_c1_tables.py). Orin's C1
verdicts are parsed from reference/orin/reports/E4g_c1_c2_bottlenecks.md and printed beside Thor's, labelled Orin.

c2_eager_vs_best.csv needs both modes of a model; rows without eager_fp32 say so. Every Thor number is read from the CSVs.

python bench/make_e4g_report.py --date 20261025
"""
import argparse
import csv
import glob
import json
import os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODELS = ["pi0", "pi05", "smolvla", "groot_n17", "groot_n16", "groot_n15"]
NAMES = {"pi0": "π0", "pi05": "π0.5", "smolvla": "SmolVLA", "groot_n17": "GR00T N1.7", "groot_n16": "GR00T N1.6",
         "groot_n15": "GR00T N1.5"}
COLS = ["model", "mode", "part", "n_kernels", "coverage", "kernel_ms", "idle_frac", "sm_pct", "onchip_mem_pct", "occupancy_pct",
        "tensor_pipe_pct", "dram_GBps", "pct_peak_bw", "top_stall", "top_stall_share", "verdict"]
ORIN_PART = {"ae_step_0": "ae_step[0]"}


def latest(m, mode):
    ds = [d for d in sorted(glob.glob(os.path.join(REPO, "results", f"*_E4g_c1_{m}_{mode}")))
          if os.path.exists(os.path.join(d, "meta.json")) and not os.path.exists(os.path.join(d, "SUPERSEDED.md"))]
    return ds[-1] if ds else None


def orin_c1():
    out = {}
    for line in open(os.path.join(REPO, "reference", "orin", "reports", "E4g_c1_c2_bottlenecks.md")):
        c = [x.strip() for x in line.strip().strip("|").split("|")]
        if len(c) == 9 and c[0] in MODELS and c[1] in ("eager", "best"):
            part = ORIN_PART.get(c[2].strip("`"), c[2].strip("`"))
            out[(c[0], c[1], part)] = {"sm": c[3], "mem": c[4], "occ": c[5], "top": c[7], "verdict": c[8]}
    return out


def f(x, nd=1):
    try:
        return f"{float(x):.{nd}f}"
    except (TypeError, ValueError):
        return "—"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--date", required=True)
    ap.add_argument("--report", default=os.path.join(REPO, "reports", "E4g_c1_c2_bottlenecks.md"))
    a = ap.parse_args()
    out = os.path.join(REPO, "results", f"{a.date}_E4g_c1_summary")
    os.makedirs(out, exist_ok=True)
    rows, srcs = [], {}
    for mode in ("best_bf16", "eager_fp32"):
        for m in MODELS:
            d = latest(m, mode)
            if not d:
                continue
            srcs[(m, mode)] = os.path.relpath(d, REPO)
            for r in csv.DictReader(open(os.path.join(d, "ncu", "region_utilisation.csv"))):
                rows.append({k: r.get(k, "") for k in COLS} | {"source": os.path.relpath(d, REPO),
                            **{k: r[k] for k in r if k.startswith("time_share_")}})
    keys = []
    for r in rows:
        keys += [k for k in r if k not in keys]
    with open(os.path.join(out, "c1_bounds.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=keys)
        w.writeheader()
        w.writerows(rows)
    by = {(r["model"], r["mode"], r["part"]): r for r in rows}
    c2 = []
    for (m, mode, part), b in sorted(by.items()):
        if mode != "best_bf16":
            continue
        e = by.get((m, "eager_fp32", part))
        if not e:
            c2.append({"model": m, "part": part, "eager_verdict": "not captured yet", "best_verdict": b["verdict"]})
            continue
        d = {k: float(b[k] or 0) - float(e[k] or 0) for k in ("sm_pct", "onchip_mem_pct", "occupancy_pct", "tensor_pipe_pct",
                                                               "dram_GBps", "top_stall_share")}
        c2.append({"model": m, "part": part, "eager_verdict": f"{e['verdict']} ({e['top_stall']})",
                   "best_verdict": f"{b['verdict']} ({b['top_stall']})", **{f"delta_{k}": round(v, 3) for k, v in d.items()},
                   "eager_kernel_ms": e["kernel_ms"], "best_kernel_ms": b["kernel_ms"]})
    keys = []
    for r in c2:
        keys += [k for k in r if k not in keys]
    with open(os.path.join(out, "c2_eager_vs_best.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=keys)
        w.writeheader()
        w.writerows(c2)
    json.dump({"sources": {f"{m} {mode}": s for (m, mode), s in srcs.items()}}, open(os.path.join(out, "sources.json"), "w"), indent=1)
    orin = orin_c1()
    L = ["# E4g — what each part is bound by (C1), and what the optimisation changed (C2) (T007)", "",
         f"**Generated by `bench/make_e4g_report.py` from `results/{a.date}_E4g_c1_summary/`** (the latest C1 directory per "
         "model × mode, `bench/t007_c1.py` + `bench/t007_c1_tables.py`). Nothing here is typed in.", "",
         "**How to read it.** ncu `--set full` plus the 17 warp-stall reasons, tensor-pipe and T003's DRAM / FLOP counters, on "
         "**every kernel** of each part (chunked windows; coverage = joined nsys kernel time ÷ the part's nsys kernel time). "
         "Every per-part value is weighted by nsys kernel time. Per kernel, the speed-of-light verdict: compute-bound if SM % "
         "≥ 80 and ≥ memory; memory-bound if memory ≥ 80, where memory = max(on-chip memory %, DRAM % of the measured 258.2 "
         "GB/s) because this chip exposes no `dram__` counters, so ncu's own memory % omits DRAM; otherwise latency-bound, "
         "named by its largest stall; launch-bound if shorter than the part's median launch gap. The part's verdict is the "
         "class holding most of its kernel time; the time shares are given. **DRAM GB/s** = ncu bytes ÷ nsys duration; ncu "
         "flushes the caches before each replay, so the bytes are cold-L2 bytes and the rate can exceed what the run moves "
         "(it exceeds the measured peak where the real run hits in L2).", "",
         "## C1 — the verdict per part", "",
         "| model | mode | part | kernels | coverage | kernel ms | SM % | on-chip mem % | DRAM GB/s (% peak) | occupancy % | "
         "tensor pipe % | top stall (share) | verdict | time: memory / latency / compute / launch | Orin (same mode class): verdict, top stall |",
         "|" + "---|" * 15]
    for r in rows:
        o = orin.get((r["model"], "best" if r["mode"] == "best_bf16" else "eager", r["part"]))
        ts = " / ".join(f"{float(r.get(f'time_share_{c}') or 0) * 100:.0f} %" for c in ("memory-bound", "latency-bound", "compute-bound", "launch-bound"))
        L.append(f"| {NAMES[r['model']]} | {r['mode']} | `{r['part']}` | {r['n_kernels']} | {f(float(r['coverage']) * 100)} % | "
                 f"{f(r['kernel_ms'], 2)} | {f(r['sm_pct'])} | {f(r['onchip_mem_pct'])} | {f(r['dram_GBps'], 0)} ({f(r['pct_peak_bw'], 0)} %) | "
                 f"{f(r['occupancy_pct'])} | {f(r['tensor_pipe_pct'])} | {r['top_stall']} ({f(float(r['top_stall_share'] or 0) * 100, 0)} %) | "
                 f"**{r['verdict']}** | {ts} | " + (f"{o['verdict']}, {o['top']} (Orin)" if o else "—") + " |")
    L += ["", "Orin values: `reference/orin/reports/E4g_c1_c2_bottlenecks.md` §C1 (its own rule set and its `best` rung, which "
          "differs from Thor's `best_bf16`).", "", "## C2 — eager_fp32 → best_bf16", ""]
    if any("delta_sm_pct" in r for r in c2):
        L += ["| model | part | eager verdict | best verdict | Δ SM % | Δ on-chip mem % | Δ DRAM GB/s | Δ tensor pipe % | Δ top-stall share | kernel ms eager → best |",
              "|" + "---|" * 10]
        for r in c2:
            if "delta_sm_pct" in r:
                L.append(f"| {NAMES[r['model']]} | `{r['part']}` | {r['eager_verdict']} | {r['best_verdict']} | {r['delta_sm_pct']:+.1f} | "
                         f"{r['delta_onchip_mem_pct']:+.1f} | {r['delta_dram_GBps']:+.0f} | {r['delta_tensor_pipe_pct']:+.1f} | "
                         f"{r['delta_top_stall_share'] * 100:+.0f} pp | {f(r['eager_kernel_ms'], 2)} → {f(r['best_kernel_ms'], 2)} |")
    missing = [f"{NAMES[r['model']]} `{r['part']}`" for r in c2 if "delta_sm_pct" not in r]
    if missing:
        L += ["", f"Not yet comparable (eager_fp32 C1 not captured yet): {', '.join(missing)}."]
    L += ["", "Sources: " + "; ".join(f"`{s}`" for s in srcs.values()), ""]
    open(a.report, "w").write("\n".join(L) + "\n")
    print(f"{len(rows)} part rows, {len(c2)} C2 rows -> {out}, {a.report}")


if __name__ == "__main__":
    main()
