"""T007: reports/E5_timeline.md from the committed results/*_E5_<model>_<mode>_timeline/ directories (bench/t007_timeline.py).
Every Thor number is read from those CSVs; Orin's are quoted from reference/orin/reports/E5_timeline.md and labelled.

python bench/make_e5_report.py
"""
import argparse
import csv
import glob
import os
import statistics

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODELS = ["pi0", "pi05", "smolvla", "groot_n17", "groot_n16", "groot_n15"]
NAMES = {"pi0": "π0", "pi05": "π0.5", "smolvla": "SmolVLA", "groot_n17": "GR00T N1.7", "groot_n16": "GR00T N1.6",
         "groot_n15": "GR00T N1.5"}
SHOW = ("vision", "vlm_prefix", "backbone_lm_head", "ae_step", "ae_total", "inference")


def latest(m, mode):
    ds = [d for d in sorted(glob.glob(os.path.join(REPO, "results", f"*_E5_{m}_{mode}_timeline")))
          if os.path.exists(os.path.join(d, "meta.json")) and not os.path.exists(os.path.join(d, "SUPERSEDED.md"))]
    return ds[-1] if ds else None


def fnum(x, nd=2):
    try:
        return f"{float(x):,.{nd}f}"
    except (TypeError, ValueError):
        return "—"


def pct(x):
    try:
        return f"{float(x) * 100:.1f} %"
    except (TypeError, ValueError):
        return "—"


def agg(rows, region):
    """Mean over the capture's inferences (and, for ae_step, over its steps) of one region's rows."""
    sel = [r for r in rows if (r["region"].startswith("ae_step[") if region == "ae_step" else r["region"] == region)]
    if not sel:
        return None
    out = {"n": len(sel)}
    for k in ("wall_ms_nsys", "kernel_union_ms", "kernel_sum_ms", "gpu_idle_frac_nsys", "event_ms_t005", "gpu_idle_frac_vs_event",
              "kernels", "graph_nodes", "gap_median_us", "starved_frac_of_gaps", "starved_gap_ms", "intra_graph_gap_ms", "queued_gap_ms"):
        vals = [float(r[k]) for r in sel if r.get(k) not in (None, "")]
        out[k] = statistics.mean(vals) if vals else None
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(REPO, "reports", "E5_timeline.md"))
    a = ap.parse_args()
    L = ["# E5 — is the GPU working, or waiting for the CPU? (T007 step 1)", "",
         "**Generated by `bench/make_e5_report.py` from the committed `results/*_E5_<model>_<mode>_timeline/` directories** "
         "(`bench/t007_timeline.py` on T006's nsys captures, two inferences each). Nothing here is typed in.", "",
         "Definitions (as `reference/orin/bench/parse_nsys.py`): **wall** = the GPU-projected NVTX range in the nsys capture; "
         "**kernel union** = the union of kernel intervals inside it; **GPU idle** = wall − union. nsys tracing stretches "
         "ranges, so idle is also given against the untraced CUDA-event time of the same configuration's T005 row "
         "(**idle vs event** = 1 − union ÷ event time; negative values mean the traced kernels took longer than the event "
         "median, i.e. no measurable idle). Gaps between consecutive kernels are split: **intra-graph** (two nodes of one "
         "CUDA-graph launch), **CPU-starved** (the next kernel's launch call returned only after the previous kernel had "
         "finished: the GPU had nothing queued) and **queued** (work was submitted; launch latency or a device dependency). "
         "`ae_step` rows are the mean per denoising step over all steps of both inferences; other rows are per inference.", ""]
    for mode in ("best_bf16", "eager_fp32"):
        L += [f"## {mode}", "",
              "| model | region | wall ms (nsys) | kernel union ms | event ms (T005) | idle (nsys) | idle vs event | kernels | "
              "graph nodes | gap median µs | CPU-starved gap ms | intra-graph gap ms | queued gap ms | starved share of gaps |",
              "|" + "---|" * 14]
        cls_lines = []
        for m in MODELS:
            d = latest(m, mode)
            if not d:
                L.append(f"| {NAMES[m]} | not analysed yet | | | | | | | | | | | | |")
                continue
            rows = [r for r in csv.DictReader(open(os.path.join(d, "timeline_summary.csv")))]
            for reg in SHOW:
                g = agg(rows, reg)
                if not g:
                    continue
                L.append(f"| {NAMES[m]} | `{reg}` | {fnum(g['wall_ms_nsys'])} | {fnum(g['kernel_union_ms'])} | {fnum(g['event_ms_t005'])} | "
                         f"{pct(g['gpu_idle_frac_nsys'])} | {pct(g['gpu_idle_frac_vs_event'])} | {fnum(g['kernels'], 0)} | "
                         f"{fnum(g['graph_nodes'], 0)} | {fnum(g['gap_median_us'], 1)} | {fnum(g['starved_gap_ms'], 3)} | "
                         f"{fnum(g['intra_graph_gap_ms'], 3)} | {fnum(g['queued_gap_ms'], 3)} | {pct(g['starved_frac_of_gaps'])} |")
            cl = list(csv.DictReader(open(os.path.join(d, "kernel_classes.csv"))))
            for reg in SHOW:
                sel = [r for r in cl if (r["region"].startswith("ae_step[") if reg == "ae_step" else r["region"] == reg)]
                if not sel:
                    continue
                tot = sum(float(r["ms"]) for r in sel) or 1
                share = {c: sum(float(r["ms"]) for r in sel if r["class"] == c) / tot
                         for c in ("GEMM", "attention", "norm", "elementwise", "copy", "other")}
                cls_lines.append(f"| {NAMES[m]} | `{reg}` | " + " | ".join(pct(share[c]) for c in share) + " |")
            cpu_p = os.path.join(d, "cpu_thread.csv")
            if os.path.exists(cpu_p):
                cpu = list(csv.DictReader(open(cpu_p)))
                L_cpu = []
                for reg in SHOW:
                    sel = [r for r in cpu if (r["region"].startswith("ae_step[") if reg == "ae_step" else r["region"] == reg)]
                    if sel:
                        mean = lambda k: statistics.mean(float(r[k]) for r in sel if r[k] != "")  # noqa: E731
                        L_cpu.append(f"`{reg}` CPU range {mean('cpu_range_ms'):.2f} ms, CUDA API {mean('cuda_api_ms'):.2f} ms in "
                                     f"{mean('cuda_api_calls'):.0f} calls ({mean('graph_launch_calls'):.0f} graph launches), "
                                     f"on-CPU {mean('on_cpu_frac') * 100:.0f} %")
                L.append(f"| | *{NAMES[m]} launching thread:* {'; '.join(L_cpu)} | | | | | | | | | | | | |")
            L.append(f"| | *source: `{os.path.relpath(d, REPO)}`* | | | | | | | | | | | | |")
        L += ["", f"Kernel classes by kernel time ({mode}; rules in `bench/t007_timeline.py`):", "",
              "| model | region | GEMM | attention | norm | elementwise | copy | other |", "|" + "---|" * 8] + cls_lines + [""]
    L += ["## Orin (labelled Orin; `reference/orin/reports/E5_timeline.md`, \"Per region\" table)", "",
          "Orin's expert step was mostly GPU-idle when eager (π0 `eager` ae_step idle 84 %, corrected 76 %; π0.5 64 %, "
          "corrected 47 %) and still 45–47 % idle in its best π0 / π0.5 configuration; GR00T's compiled action head was "
          "≈ 0.1 % idle (N1.5 / N1.6 / N1.7 `best` ae_total 0.08–0.10 %), while N1.7's eager vision and prefix were 42 % and "
          "64 % idle. See that file for the full table.", ""]
    open(a.out, "w").write("\n".join(L) + "\n")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
