"""T006 step 6: reports/E6_<model>_roofline.md (six) and reports/E6_roofline_all.md from the E6 result directories
(roofline.csv, floor.csv, kernel_roofline.csv, coverage.json; bench/t006_roofline.py). Every Thor number is read from those
files. The Orin's values are parsed from reference/orin/reports/E6_*.md at generation time and labelled Orin.

python bench/make_e6_reports.py
"""
import argparse
import collections
import csv
import glob
import json
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODELS = ["pi0", "pi05", "smolvla", "groot_n17", "groot_n16", "groot_n15"]
NAMES = {"pi0": "π0", "pi05": "π0.5", "smolvla": "SmolVLA", "groot_n17": "GR00T N1.7", "groot_n16": "GR00T N1.6",
         "groot_n15": "GR00T N1.5"}
COLD = "per-kernel replay"
SEQ = "range replay"


def latest(m, mode):
    ds = [d for d in sorted(glob.glob(os.path.join(REPO, "results", f"*_E6_{m}_{mode}*")))
          if not os.path.exists(os.path.join(d, "SUPERSEDED.md")) and os.path.exists(os.path.join(d, "roofline.csv"))]
    return ds[-1] if ds else None


def f(x, nd=2):
    try:
        return f"{float(x):,.{nd}f}"
    except (TypeError, ValueError):
        return "—"


def orin_rows():
    """Orin E6 rows, parsed: {model: [(label, region, ms, % peak BW, gap, source)]}."""
    out = collections.defaultdict(list)
    for m in ("pi0", "pi05", "smolvla"):
        p = os.path.join(REPO, "reference", "orin", "reports", f"E6_{m}_roofline.md")
        if not os.path.exists(p):
            continue
        for i, ln in enumerate(open(p), 1):
            c = [x.strip().strip("*") for x in ln.strip().strip("|").split("|")]
            if len(c) in (7, 8) and re.match(r"`(vision|vlm_prefix|ae_step)`", c[0]):
                bwc, gapc = (4, 7) if len(c) == 8 else (3, 6)       # π0's table has a "side" column, π0.5 / SmolVLA's not
                out[m].append(("eager", c[0].strip("`"), c[1], c[bwc], c[gapc], f"reference/orin/reports/E6_{m}_roofline.md:{i}"))
            if len(out[m]) >= 3:
                break
    p = os.path.join(REPO, "reference", "orin", "reports", "E6_groot_roofline.md")
    for i, ln in enumerate(open(p), 1):
        mm = re.match(r">\s*\|\s*`([a-z_0-9]+)`[^|]*\|\s*([\d.]+)\s*\|\s*([\d.]+)\s*\|\s*\**([\d.]+) %\**\s*\|\s*\**([\d.]+)×\**", ln)
        if mm and mm.group(1) in ("eager_tf32", "eager_fp32", "ae_graphs"):
            out["groot_n17"].append((mm.group(1), "ae_step", mm.group(2), mm.group(4) + " %", mm.group(5) + "×",
                                     f"reference/orin/reports/E6_groot_roofline.md:{i} (correction block)"))
    return out


def part_rows(d):
    rf = list(csv.DictReader(open(os.path.join(d, "roofline.csv"))))
    fl = {r["region"]: r for r in csv.DictReader(open(os.path.join(d, "floor.csv"))) if r["peak_source"] == "measured"}
    fls = {r["region"]: r for r in csv.DictReader(open(os.path.join(d, "floor.csv"))) if r["peak_source"].startswith("spec")}
    cov = json.load(open(os.path.join(d, "coverage.json")))
    parts = []
    for p in sorted({r["part"] for r in rf}):
        get = lambda src, basis: next((r for r in rf if r["part"] == p and r["source"] == src and r["time_source"] == "region_cuda_event"  # noqa: E731
                                       and r["bytes_basis"].startswith(basis)), None)
        parts.append((p, get("analytic", "weights"), get("ncu", COLD), get("ncu", SEQ), fl.get(p, {}), fls.get(p, {}), cov.get(p, {})))
    return parts, fl, fls


def model_report(m, out, orin):
    L = [f"# E6 — {NAMES[m]} on Thor's measured roofline (T006)", "",
         "**Generated by `bench/make_e6_reports.py` from the E6 result files**; no number is typed. Ceilings are this device's "
         "measured ones (`results/20261022_E1_peak/hw_constants.json`: 258.2 GB/s; bf16 129.8, TF32 62.4, fp32 SIMT 6.43 TFLOP/s); "
         "the spec bandwidth (273 GB/s, NVIDIA) is in `floor.csv` (NVIDIA publishes no dense per-dtype tensor figure for Thor). "
         "Part times are the T005 CUDA-event regions of the same configuration; kernel times are nsys.", "",
         "**Three byte counts per part, because they answer different questions:**", "",
         "- **analytic** — the floor's bytes (protocol §9): weights once per call or denoising step + the KV / hand-over read + the "
         "GEMM operand activations from C3; FLOPs from the real (unpadded) M.",
         "- **ncu, in sequence** — range replay of the whole part with the caches not flushed: what the back-to-back sequence "
         "actually moves through DRAM. **This is the column the verdict uses.**",
         "- **ncu, cold L2** — per-kernel replay, caches flushed before each kernel (ncu's default): every kernel's inputs counted "
         "as DRAM traffic even when the previous kernel left them in the 32 MiB L2. An upper bound; per-kernel rates above 100 % "
         "of the bandwidth ceiling come from it.", ""]
    for mode in ("best_bf16", "eager_fp32"):
        d = latest(m, mode)
        if not d:
            L += [f"## {mode}: not captured yet", ""]
            continue
        parts, fl, fls = part_rows(d)
        L += [f"## {mode} (`{os.path.relpath(d, REPO)}`)", "",
              "| part | time ms (CUDA event) | FLOPs analytic / ncu | DRAM bytes: analytic / in sequence / cold L2 | intensity (in seq.) | "
              "% peak BW (in seq.) | % peak compute (ncu) | side of the ridge: analytic / in seq. / cold L2 | floor ms | gap × floor | "
              "coverage (strict join) | SM clock MHz |", "|" + "---|" * 12]
        for p, an, cold, seq, flr, fls_, cv in parts:
            ref = seq or cold
            clk = cv.get("sm_clock_MHz", {})
            clk = f"{clk['median']:.0f} ({clk['min']:.0f}–{clk['max']:.0f})" if isinstance(clk, dict) else "—"
            L.append(f"| `{p}` | {f(an['ms'] if an else (ref or {}).get('ms'))} | "
                     f"{float(an['flops']):.3e} / {float((cold or {}).get('flops', 0)):.3e} | "
                     f"{float(an['bytes']):.3e} / {(f'{float(seq['bytes']):.3e}' if seq else 'not captured')} / {float(cold['bytes']):.3e} | "
                     f"{f(ref['intensity'], 1)} | {f(ref['pct_peak_bw'], 1)} % | {f((cold or {}).get('pct_peak_compute'), 1)} % | "
                     f"{an['bound'] if an else '—'} / {seq['bound'] if seq else '—'} / {cold['bound']} (ridge {f(cold['ridge'], 0)}) | "
                     f"{f(flr.get('floor_ms'), 3)} ({flr.get('bound', '—')}) | {f(flr.get('gap_ratio'))} | "
                     f"{f(cv.get('coverage_pct'), 1)} % ({cv.get('join_name_only', '—')} name-only, {cv.get('join_none', '—')} unmatched) | {clk} |")
        L += ["", "**Floors** (`floor.csv`, protocol §9; bytes = weights + KV + GEMM activations; spec row = bandwidth only):", "",
              "| part | bytes read (weights / KV / activations) | FLOPs | floor ms, measured ceilings | floor ms, spec bandwidth | "
              "weight-only floor ms | measured ms | gap × floor | notes |", "|" + "---|" * 9]
        for r in csv.DictReader(open(os.path.join(d, "floor.csv"))):
            if r["peak_source"] != "measured":
                continue
            s = fls.get(r["region"], {})
            L.append(f"| `{r['region']}` | {float(r['bytes_read']):.3e} ({float(r['bytes_weights']):.2e} / {float(r['bytes_kv']):.1e} / "
                     f"{float(r['bytes_activations']):.2e}) | {float(r['flops']):.3e} | {f(r['floor_ms'], 3)} ({r['bound']}) | "
                     f"{f(s.get('floor_ms'), 3)} | {f(r['floor_mem_weights_only_ms'], 3)} | {f(r['measured_ms'])} | {f(r['gap_ratio'])} | {r['notes'] or '—'} |")
        kr = [k for k in csv.DictReader(open(os.path.join(d, "kernel_roofline.csv"))) if k["ms_nsys"]]
        over = [k for k in kr if k["over_100pct"]]
        tot = sum(float(k["ms_nsys"]) for k in kr) or 1
        L += ["", f"**Kernels whose ncu rate exceeds a ceiling:** {len(over)} of {len(kr)} joined launches, "
              f"{sum(float(k['ms_nsys']) for k in over) / tot * 100:.1f} % of their time. Their bytes are cold-L2 bytes or their "
              "tensor FLOPs include tile padding (both counted as executed); the in-sequence column above is the part's real traffic.", ""]
        agg = collections.defaultdict(lambda: {"n": 0, "ms": 0.0, "b": 0, "f": 0, "part": "", "cls": "", "dt": "", "ceil": 0, "ridge": 0})
        for k in kr:
            g = agg[(k["part"], k["kernel"][:90])]
            g["n"] += 1
            g["ms"] += float(k["ms_nsys"])
            g["b"] += int(k["bytes_ncu"])
            g["f"] += int(k["flops_ncu"])
            g["part"], g["cls"], g["dt"], g["ceil"], g["ridge"] = k["part"], k["op_class"], k["dtype"], float(k["ceiling_TFLOPps"]), float(k["ridge_flop_per_B"])
        L += [f"Ten heaviest kernels ({mode}; launches of one kernel aggregated; nsys time; cold-L2 ncu bytes):", "",
              "| part | kernel | class | launches | ms | % of the part's kernel time | roof (dtype, TFLOP/s) | intensity | TFLOP/s | GB/s | side |",
              "|" + "---|" * 11]
        ptot = collections.Counter()
        for (p, _), g in agg.items():
            ptot[p] += g["ms"]
        for (p, name), g in sorted(agg.items(), key=lambda x: -x[1]["ms"])[:10]:
            inten = g["f"] / g["b"] if g["b"] else None
            L.append(f"| `{p}` | `{name[:70]}` | {g['cls']} | {g['n']} | {g['ms']:.3f} | {g['ms'] / ptot[p] * 100:.1f} % | "
                     f"{g['dt']} {g['ceil']:.1f} | {f(inten, 1)} | {g['f'] / (g['ms'] / 1e3) / 1e12:.2f} | {g['b'] / (g['ms'] / 1e3) / 1e9:.1f} | "
                     f"{('compute' if inten >= g['ridge'] else 'memory') if inten is not None else '—'} |")
        L += ["", "**Where analytic and measured bytes disagree, and by how much** (in-sequence ÷ analytic; the cold-L2 ratio in brackets):", ""]
        for p, an, cold, seq, flr, fls_, cv in parts:
            if not an:
                continue
            r_seq = float(seq["bytes"]) / float(an["bytes"]) if seq and float(an["bytes"]) else None
            r_cold = float(cold["bytes"]) / float(an["bytes"]) if float(an["bytes"]) else None
            L.append(f"- `{p}`: {f(r_seq) if r_seq else 'in-sequence not captured'}× ({f(r_cold)}× cold L2). "
                     + ("Close to the analytic minimum." if r_seq and 0.8 <= r_seq <= 1.25 else
                        "More than the analytic minimum: activations the analytic model does not count (norm / elementwise / "
                        "attention intermediates; C3 counts GEMM operands only) and weights re-read within the part."
                        if r_seq and r_seq > 1.25 else
                        "Less than the analytic count: part of the analytic activations stay in L2." if r_seq else ""))
        L += ["", f"Plot: `{os.path.relpath(os.path.join(d, 'roofline.png'), REPO)}`.", ""]
    if orin.get(m):
        L += ["**Orin** (labelled Orin; parsed from its reports at generation time):", ""]
        L += [f"- Orin {lab} `{reg}`: {ms} ms, {bw} of its peak bandwidth, gap {gap} — `{src}`" for lab, reg, ms, bw, gap, src in orin[m]]
        L.append("")
    open(os.path.join(out, f"E6_{m}_roofline.md"), "w").write("\n".join(L) + "\n")
    return [(m, mode) for mode in ("best_bf16", "eager_fp32") if latest(m, mode)]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(REPO, "reports"))
    a = ap.parse_args()
    orin = orin_rows()
    have = []
    for m in MODELS:
        have += model_report(m, a.out, orin)
    L = ["# E6 — all six models on Thor's measured roofline (T006)", "",
         "**Generated by `bench/make_e6_reports.py`.** One row per model × mode × part. Time = the T005 CUDA-event region median of "
         "the same configuration. The verdict uses the **in-sequence** DRAM bytes (ncu range replay, caches not flushed); the "
         "analytic side and the cold-L2 side (per-kernel replay) are beside it. Floor and gap from `floor.csv` (protocol §9: "
         "weights + KV + GEMM activations, real M). Per-model detail: `reports/E6_<model>_roofline.md`.", "",
         "| model | mode | part | ms | intensity (in seq.) | % peak compute | % peak BW (in seq.) | side: analytic / in seq. / cold L2 | "
         "floor ms | gap × floor | coverage (strict) |", "|" + "---|" * 11]
    for m, mode in have:
        d = latest(m, mode)
        parts, fl, fls = part_rows(d)
        for p, an, cold, seq, flr, fls_, cv in parts:
            ref = seq or cold
            L.append(f"| {NAMES[m]} | {mode} | `{p}` | {f(an['ms'] if an else ref['ms'])} | {f(ref['intensity'], 1)} | "
                     f"{f(cold['pct_peak_compute'], 1)} % | {f(ref['pct_peak_bw'], 1)} %{'' if seq else ' (cold L2: in-seq. not captured)'} | "
                     f"{an['bound'] if an else '—'} / {seq['bound'] if seq else '—'} / {cold['bound']} | {f(flr.get('floor_ms'), 3)} | "
                     f"{f(flr.get('gap_ratio'))} | {f(cv.get('coverage_pct'), 1)} % |")
    L += ["", "**Orin E6** (labelled Orin; parsed from `reference/orin/reports/E6_*.md`; the Orin's GR00T row was corrected there: its "
          "first-reported 'ae_step' was the CUDA-graphed head, the eager rows are in its correction block):", ""]
    for m, rows in orin.items():
        L += [f"- {NAMES[m]} — Orin {lab} `{reg}`: {ms} ms, {bw} of peak BW, gap {gap} (`{src}`)" for lab, reg, ms, bw, gap, src in rows]
    open(os.path.join(a.out, "E6_roofline_all.md"), "w").write("\n".join(L) + "\n")
    print(f"wrote {len(MODELS)} model reports and E6_roofline_all.md ({len(have)} model x mode)")


if __name__ == "__main__":
    main()
