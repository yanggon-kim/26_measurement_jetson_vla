"""T006 step 6: generate reports/E6_<model>_roofline.md (six) and reports/E6_roofline_all.md from the E6 result
directories (roofline.csv, floor.csv, kernel_roofline.csv, coverage.json). Every Thor number is read from those files;
the Orin's E6 values are quoted with their source and labelled Orin.

python bench/make_e6_reports.py --date 20261024
"""
import argparse
import csv
import glob
import json
import os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODELS = ["pi0", "pi05", "smolvla", "groot_n17", "groot_n16", "groot_n15"]
NAMES = {"pi0": "π0", "pi05": "π0.5", "smolvla": "SmolVLA", "groot_n17": "GR00T N1.7", "groot_n16": "GR00T N1.6",
         "groot_n15": "GR00T N1.5"}
# Orin E6 (eager, per denoising step), quoted from reference/orin/reports/E6_groot_roofline.md lines 48-53
ORIN_AE = {"pi0": ("52.79 ms, 638 MB/step, 6.45 % of peak BW, gap 15.51×", "E6_groot_roofline.md:50"),
           "pi05": ("62.69 ms, 1 735 MB/step, 14.76 %, gap 6.77×", "E6_groot_roofline.md:51"),
           "smolvla": ("60.80 ms, 203 MB/step, 1.78 %, gap 56.04×", "E6_groot_roofline.md:52"),
           "groot_n17": ("20.06 ms, 3 241 MB/step, 86.17 %, gap 1.161×", "E6_groot_roofline.md:53")}


def latest(m, mode):
    ds = [d for d in sorted(glob.glob(os.path.join(REPO, "results", f"*_E6_{m}_{mode}*")))
          if not os.path.exists(os.path.join(d, "SUPERSEDED.md")) and os.path.exists(os.path.join(d, "roofline.csv"))]
    return ds[-1] if ds else None


def f(x, nd=2):
    try:
        return f"{float(x):,.{nd}f}"
    except (TypeError, ValueError):
        return "—"


def model_report(m, out):
    L = [f"# E6 — {NAMES[m]} on Thor's measured roofline (T006)", "",
         "**Generated by `bench/make_e6_reports.py` from the E6 result files**; no number is typed. Roofs are this "
         "device's measured ceilings (`results/20261022_E1_peak/hw_constants.json`: 258.2 GB/s, bf16 129.8 TFLOP/s, fp32 "
         "SIMT 6.43, TF32 62.4). DRAM bytes and FLOPs come from the counters T003 validated: DRAM bytes = "
         "(`lts__d_sectors_fill_sysmem` + `lts__t_sectors_aperture_sysmem_op_write`) × 32; tensor FLOPs = Σ "
         "`sm__ops_path_tensor_src_*`, which counts tile-padded work; SIMT FLOPs from the sass add / mul / fma counters. "
         "Kernel times come from nsys; part times from the T005 CUDA-event regions of the same configuration.", ""]
    rows_all = []
    for mode in ("best_bf16", "eager_fp32"):
        d = latest(m, mode)
        if not d:
            L += [f"## {mode}: not captured yet", ""]
            continue
        rf = list(csv.DictReader(open(os.path.join(d, "roofline.csv"))))
        fl = {r["part"]: r for r in csv.DictReader(open(os.path.join(d, "floor.csv")))}
        cov = json.load(open(os.path.join(d, "coverage.json")))
        L += [f"## {mode} (`{os.path.relpath(d, REPO)}`)", "",
              "| part | time ms (CUDA event) | FLOPs (ncu) | DRAM bytes (ncu) | intensity FLOP/B | TFLOP/s | GB/s | % peak compute "
              "| % peak BW | side of the ridge | analytic bytes | measured ÷ analytic bytes | floor ms | gap × floor | coverage |",
              "|" + "---|" * 15]
        for r in rf:
            if not r["source"].startswith("ncu, time = CUDA"):
                continue
            an = next((x for x in rf if x["part"] == r["part"] and x["source"].startswith("analytic")), {})
            fr = fl.get(r["part"], {})
            ratio = (float(r["dram_bytes"]) / float(an["dram_bytes"])) if an.get("dram_bytes") not in (None, "", "0") else None
            L.append(f"| `{r['part']}` | {f(r['time_ms'])} | {float(r['flops']):.3e} | {float(r['dram_bytes']):.3e} | {f(r['intensity'], 1)} | "
                     f"{f(r['achieved_TFLOPps'])} | {f(r['achieved_GBps'], 1)} | {f(r['pct_peak_compute'], 1)} % | {f(r['pct_peak_bw'], 1)} % | "
                     f"{r['bound']} (ridge {f(r['ridge'], 0)}) | {float(an.get('dram_bytes', 0) or 0):.3e} | {f(ratio)} | "
                     f"{f(fr.get('floor_ms'), 3)} | {f(fr.get('gap_ratio'))} | {f(cov.get(r['part'], {}).get('coverage_pct'), 1)} % |")
            rows_all.append((m, mode, r, fr, cov.get(r["part"], {})))
        kr = list(csv.DictReader(open(os.path.join(d, "kernel_roofline.csv"))))
        kr = [k for k in kr if k["nsys_duration_ns"]]
        kr.sort(key=lambda k: -int(k["nsys_duration_ns"]))
        L += ["", f"Five heaviest kernels per part ({mode}, by nsys time). `roof` = the ceiling the kernel is judged against: "
              "the tensor-core rate of the dtype it executes, or the fp32 SIMT rate for a kernel with no tensor instructions.", "",
              "| part | kernel | grid | µs | roof | intensity | TFLOP/s | GB/s | % peak compute | % peak BW | side |", "|" + "---|" * 11]
        for part in sorted({k["part"] for k in kr}):
            for k in [k for k in kr if k["part"] == part][:5]:
                L.append(f"| `{k['part']}` | `{k['kernel'][:70]}` | {k['grid']} | {int(k['nsys_duration_ns']) / 1e3:.1f} | "
                         f"{k['compute_dtype']} {f(k['ceiling_TFLOPps'], 1)} | {f(k['intensity_flop_per_B'], 1)} | {f(k['achieved_TFLOPps'])} | "
                         f"{f(k['achieved_GBps'], 1)} | {f(k['pct_peak_compute'], 1)} | {f(k['pct_peak_bw'], 1)} | {k['bound_by_intensity']} |")
        L += ["", f"Plot: `{os.path.relpath(os.path.join(d, 'roofline.png'), REPO)}`.", ""]
    if m in ORIN_AE:
        L += [f"Orin (eager, per denoising step): {ORIN_AE[m][0]} — `reference/orin/reports/{ORIN_AE[m][1]}`.", ""]
    open(os.path.join(out, f"E6_{m}_roofline.md"), "w").write("\n".join(L) + "\n")
    return rows_all


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(REPO, "reports"))
    a = ap.parse_args()
    allrows = []
    for m in MODELS:
        allrows += model_report(m, a.out)
    L = ["# E6 — all six models on Thor's measured roofline (T006)", "",
         "**Generated by `bench/make_e6_reports.py`.** One row per model × mode × part. Time = the T005 CUDA-event region "
         "median of the same configuration; FLOPs and DRAM bytes = ncu counters (T003-validated); floor from the analytic "
         "bytes and FLOPs at the measured ceilings; coverage = the share of the part's nsys kernel time joined to ncu. "
         "Per-model detail: `reports/E6_<model>_roofline.md`.", "",
         "| model | mode | part | ms | intensity | % peak compute | % peak BW | side | gap × floor | coverage |", "|" + "---|" * 10]
    for m, mode, r, fr, c in allrows:
        L.append(f"| {NAMES[m]} | {mode} | `{r['part']}` | {f(r['time_ms'])} | {f(r['intensity'], 1)} | {f(r['pct_peak_compute'], 1)} % | "
                 f"{f(r['pct_peak_bw'], 1)} % | {r['bound']} | {f(fr.get('gap_ratio'))} | {f(c.get('coverage_pct'), 1)} % |")
    L += ["", "Orin E6 (eager expert step, labelled Orin; `reference/orin/reports/E6_groot_roofline.md` lines 48-53):", ""]
    L += [f"- {NAMES[m]}: {v[0]}" for m, v in ORIN_AE.items()]
    open(os.path.join(a.out, "E6_roofline_all.md"), "w").write("\n".join(L) + "\n")
    print(f"wrote {len(MODELS)} model reports and E6_roofline_all.md ({len(allrows)} part rows)")


if __name__ == "__main__":
    main()
