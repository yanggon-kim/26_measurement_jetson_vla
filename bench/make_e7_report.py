"""Generate reports/E7_power_energy.md from every committed E7 run.

E7 is the campaign's empty column. Parts A, B and C measured latency and bottlenecks for
six models; until now not one power or energy number existed for any of them, and the
processing-in-memory case this study exists to test is an argument about **joules**, not
milliseconds. A phase that is 45 % of the latency and 15 % of the energy is a different
target from one that is 45 % of both.

Everything below is read from `results/*_E7_*/power.csv` at generation time. Nothing is
typed in.

## Three things this report is careful about, because each is easy to get wrong

1. **The memory rail is not DRAM power.** `VDDQ_VDD2_1V8AO` is measured at the regulator
   INPUT, at about 5.04 V, and is never rescaled to 1.8 V. It is an upper bound on DRAM
   power. It appears here under its full name with the words "(regulator input)" attached,
   and its above-idle delta is printed next to its absolute value (protocol §4).

2. **Idle is subtracted, and also shown.** A 60 s idle baseline was measured in the same
   power mode immediately before each run's loops. Both the absolute and the above-idle
   figure are given, because which one is right depends on the question: total power for a
   thermal or battery budget, above-idle for "what does this phase cost".

3. **The sampler perturbs a launch-bound workload.** The rail thread reads four sysfs
   files 20 times a second in the same process, and π0's eager `ae_step` is 84 % GPU-idle
   (E5; the frame as a whole is 55 % at N=10, and vision and the prefix are under 2 %) —
   dispatch-bound work is exactly what extra host activity slows down. So the loop's own
   median latency is printed beside the Part B median for the same configuration, and the
   difference is stated rather than left for a reader to trip over.

    python bench/make_e7_report.py --out reports/E7_power_energy.md
"""
from __future__ import annotations

import argparse
import csv
import glob
import json
from pathlib import Path

MEM = "VDDQ_VDD2_1V8AO (regulator input)"

# Part B's end-to-end median for the same model and configuration, read from the ladder
# rows so the comparison is against a committed number, not a remembered one.
LADDER = {"pi0": "results/20260922_E4c_pi0_opt_ladder",
          "pi05": "results/20260922_E4c_pi05_opt_ladder",
          "smolvla": "results/20260922_E4c_smolvla_opt_ladder",
          "groot_n17": "results/20260923_E4d_groot_n17_ladder",
          "groot_n16": "results/20260923_E4d_groot_n16_ladder",
          "groot_n15": "results/20260923_E4d_groot_n15_ladder"}
LABEL = {"pi0": "π0", "pi05": "π0.5", "smolvla": "SmolVLA",
         "groot_n17": "GR00T N1.7", "groot_n16": "GR00T N1.6", "groot_n15": "GR00T N1.5"}


def ladder_e2e(model: str, rung: str, n: int | None) -> float | None:
    d = LADDER.get(model)
    if not d:
        return None
    for p in glob.glob(f"{d}/raw/rows/*.json"):
        r = json.load(open(p))
        if r.get("rung") != rung:
            continue
        if n is not None and int(r.get("N", n)) != n:
            continue
        try:
            v = float(r["e2e_median_ms"])
        except (TypeError, ValueError, KeyError):
            continue
        if v == v:
            return v
    return None


def load_runs(pattern: str) -> list[dict]:
    runs = []
    for d in sorted(glob.glob(pattern)):
        f = Path(d) / "power.csv"
        m = Path(d) / "meta.json"
        if not f.exists():
            continue
        rows = list(csv.DictReader(f.open()))
        if not rows:
            continue
        meta = json.loads(m.read_text()) if m.exists() else {}
        runs.append({"dir": d, "rows": rows, "meta": meta})
    return runs


def num(x):
    try:
        v = float(x)
        return v if v == v else None
    except (TypeError, ValueError):
        return None


def pick(rows, phase, rail):
    for r in rows:
        if r["phase"] == phase and r["rail"] == rail:
            return r
    return None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--glob", default="results/*_E7_*")
    ap.add_argument("--out", default="reports/E7_power_energy.md")
    args = ap.parse_args()

    runs = load_runs(args.glob)
    if not runs:
        print("no E7 runs found — nothing to report")
        return 1

    L = ["# E7 — power and energy per phase, six models",
         "",
         "**Generated by `bench/make_e7_report.py` from the committed `power.csv` files.** "
         "Nothing here is typed in.",
         "",
         "This is the quantity the processing-in-memory case actually rests on. Parts A, B "
         "and C measured where the *time* goes; this measures where the *energy* goes, and "
         "the two need not agree. Every run is a 60 s idle baseline in the same power mode "
         "followed by three back-to-back loops of 60 s each — prefix-only, "
         "action-expert-only and full inference — with all four INA3221 rails sampled from "
         "sysfs at 20 Hz and tegrastats recording alongside (protocol §4).",
         "",
         "**On the memory rail.** `VDDQ_VDD2_1V8AO` is measured at the regulator **input** "
         "(~5.04 V) and is never rescaled to 1.8 V. It is an **upper bound** on DRAM power, "
         "not DRAM power. Both its absolute value and its above-idle delta are given.",
         "",
         "**On summing the rails.** T005 tested the four rails for double-counting and "
         "found none — a load that raised `VDD_GPU_SOC` by 51.8 W raised `VIN_SYS_5V0` by "
         "only 8.7 W — so `module` is their sum, and `module_without_memory_rail` is the "
         "three-rail sum for anyone who wants the memory rail excluded.",
         ""]

    # ---- headline: energy per inference, per model and configuration -------------------
    L += ["## Energy per inference", "",
          "| model | N | configuration | phase | median ms | module W | above idle W | "
          "mJ / inference | mJ above idle |",
          "|---|---:|---|---|---:|---:|---:|---:|---:|"]
    for run in runs:
        rows, meta = run["rows"], run["meta"]
        model = rows[0].get("model", meta.get("model", "?"))
        mode = rows[0].get("mode", meta.get("rung") or meta.get("compile_mode") or "?")
        n = meta.get("num_denoise_steps") or meta.get("num_inference_timesteps") or ""
        for phase in ("prefix", "ae", "full"):
            r = pick(rows, phase, "module")
            if not r:
                continue
            L.append(
                f"| {LABEL.get(model, model)} | {n} | `{mode}` | {phase} | "
                f"{num(r['median_ms']):.2f} | {num(r['mean_mW'])/1000:.2f} | "
                f"{num(r['above_idle_mW'])/1000:.2f} | "
                f"{num(r['energy_per_inference_mJ']):.1f} | "
                f"{num(r['energy_per_inference_above_idle_mJ']):.1f} |")
    L.append("")

    # ---- where the energy goes, against where the time goes ---------------------------
    L += ["## Where the energy goes, against where the time goes",
          "",
          "The share columns are of the two measured sub-phases only (`prefix` + `ae`); "
          "`full` is listed separately because it is the whole inference including the "
          "parts neither loop isolates.",
          "",
          "| model | N | configuration | prefix mJ | ae mJ | prefix % of energy | "
          "ae % of energy | prefix % of time | ae % of time |",
          "|---|---:|---|---:|---:|---:|---:|---:|---:|"]
    for run in runs:
        rows, meta = run["rows"], run["meta"]
        model = rows[0].get("model", "?")
        mode = rows[0].get("mode", "?")
        n = meta.get("num_denoise_steps") or meta.get("num_inference_timesteps") or ""
        p = pick(rows, "prefix", "module")
        a = pick(rows, "ae", "module")
        if not (p and a):
            continue
        pe = num(p["energy_per_inference_above_idle_mJ"])
        ae = num(a["energy_per_inference_above_idle_mJ"])
        pt, at = num(p["median_ms"]), num(a["median_ms"])
        if None in (pe, ae, pt, at) or pe + ae <= 0 or pt + at <= 0:
            continue
        L.append(f"| {LABEL.get(model, model)} | {n} | `{mode}` | {pe:.1f} | {ae:.1f} | "
                 f"{100*pe/(pe+ae):.1f} | {100*ae/(pe+ae):.1f} | "
                 f"{100*pt/(pt+at):.1f} | {100*at/(pt+at):.1f} |")
    L += ["",
          "**Read the last four columns against each other.** If a phase's energy share "
          "and time share are equal it draws the average power of the frame; if its energy "
          "share is higher it is the power-hungry phase, and a memory-side accelerator "
          "aimed at it saves more energy than its latency share suggests. If lower, the "
          "opposite — and the latency argument overstates the energy case.",
          ""]

    # ---- per-rail detail ---------------------------------------------------------------
    L += ["## Per-rail detail", "",
          "Every rail separately, as protocol §4 requires. `above idle` is this run's own "
          "60 s baseline in the same power mode, subtracted.",
          ""]
    for run in runs:
        rows, meta = run["rows"], run["meta"]
        model = rows[0].get("model", "?")
        mode = rows[0].get("mode", "?")
        n = meta.get("num_denoise_steps") or meta.get("num_inference_timesteps") or ""
        pm = rows[0].get("power_mode", "?")
        exec_style = rows[0].get("exec_style", "")
        L += [f"### {LABEL.get(model, model)} — `{mode}`, N={n}, {pm}"
              + (f" ({exec_style})" if exec_style else ""),
              "",
              "| phase | rail | mean mW | idle mW | above idle mW | mJ/inf | mJ/step |",
              "|---|---|---:|---:|---:|---:|---:|"]
        for r in rows:
            step = r.get("energy_per_step_mJ", "")
            L.append(f"| {r['phase']} | {r['rail']} | {num(r['mean_mW']):.0f} | "
                     f"{num(r['idle_mW']):.0f} | {num(r['above_idle_mW']):.0f} | "
                     f"{num(r['energy_per_inference_mJ']):.1f} | "
                     + (f"{num(step):.1f} |" if num(step) is not None else " |"))
        L.append("")

    # ---- the honesty section ------------------------------------------------------------
    L += ["## What these loops are, and what they are not", "",
          "**The `prefix` and `ae` loops are driven below the policy's own entry point.** "
          "`prefix` calls `embed_prefix` and the container's `forward` with "
          "`use_cache=True`; `ae` calls `denoise_step` N times on a KV cache computed once. "
          "For GR00T the equivalents are `model.backbone(...)` and "
          "`action_head.get_action(...)` on a backbone output computed once. That is the "
          "only way to isolate the action expert for a power measurement, and it has two "
          "consequences that are stated rather than buried:",
          "",
          "* A compile **mode** is applied to `sample_actions`, which sits ABOVE these two "
          "calls, so under `--modes` they run eager whatever was requested. The "
          "`exec_style` column says which: `eager_subpath` means exactly that. The runs "
          "labelled with a ladder **rung** compile `embed_image`, `container.forward` and "
          "`denoise_step` themselves, so there the loops are genuinely compiled "
          "(`compiled_subpath`).",
          "* `ae_once` drives a bounded Python loop instead of `sample_actions`' "
          "GPU-tensor `while` test. That is a documented protocol §2 deviation, made "
          "because isolating the expert requires it.",
          "",
          "**The sampler is not free.** The rail thread reads four sysfs files 20 times a "
          "second inside the measured process, and π0's eager `ae_step` is 84 % GPU-idle "
          "(E5 — the frame as a whole is 55 % at N=10, and vision and the prefix are "
          "under 2 %) — dispatch-bound work is precisely what extra host activity "
          "slows. The table "
          "below puts each loop's own median next to Part B's median for the same "
          "configuration so the perturbation is visible instead of implicit.",
          "",
          "| model | N | configuration | E7 `full` loop median ms | "
          "Part B e2e median ms | ratio |",
          "|---|---:|---|---:|---:|---:|"]
    for run in runs:
        rows, meta = run["rows"], run["meta"]
        model = rows[0].get("model", "?")
        mode = rows[0].get("mode", "?")
        r = pick(rows, "full", "module")
        if not r:
            continue
        n = meta.get("num_denoise_steps") or meta.get("num_inference_timesteps")
        rung = meta.get("rung") or ("eager_fp32" if mode == "eager" else mode)
        ref = ladder_e2e(model, rung, int(n) if n else None)
        got = num(r["median_ms"])
        L.append(f"| {LABEL.get(model, model)} | {n} | `{mode}` | {got:.2f} | "
                 + (f"{ref:.2f} | {got/ref:.2f}× |" if ref else "— | — |"))
    L += ["",
          "A ratio near 1.00 means the sampler cost nothing measurable. A ratio above 1 is "
          "the cost of measuring, and the energy-per-inference figures above carry it: "
          "they are `mean power × this loop's median`, so a slowed loop inflates the "
          "joules proportionally. Where the ratio is large, treat the **power** columns as "
          "the trustworthy ones and the **energy** columns as an upper bound.",
          ""]
    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(L) + "\n")
    print(f"wrote {args.out} ({len(L)} lines) from {len(runs)} runs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
