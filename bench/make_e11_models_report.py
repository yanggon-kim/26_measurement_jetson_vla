"""Generate reports/E11_models.md — the same hybrid-input quantities across models.

`model_inputs.csv` is the one artefact the research side reads directly to build its
processing-in-memory model. T010 produced it for π0; T011 and T012 add π0.5, SmolVLA and
GR00T. This puts them side by side, because the *differences* are what decide whether a
memory-side design generalises or was fitted to one architecture.

## The comparison has to carry P and S, not assume them

π0 processes P = 816 prefix tokens for every input — three image slots always encoded
(`empty_cameras=1`) and the prompt padded to `tokenizer_max_length=48`. π0.5 has
`tokenizer_max_length=200` and `empty_cameras=0`, so that constant does not carry over,
and GR00T is a different codebase entirely. Every row below therefore prints the P and S
that its own run measured. A table of per-segment bytes without them is unusable.

## Segments that one model has and another does not are shown as gaps, not zeros

SmolVLA has no AdaRMS gate; GR00T has no separable `softmax` (its attention is fused
under SDPA); π0 has no `adaln_cond` (its conditioning tensor is `None`). A zero would
read as "measured, and it costs nothing", which is false in all three cases. An absent
segment prints `—`.

    python bench/make_e11_models_report.py --out reports/E11_models.md
"""
from __future__ import annotations

import argparse
import csv
import glob
from collections import defaultdict
from pathlib import Path

LABEL = {"pi0": "π0", "pi05": "π0.5", "smolvla": "SmolVLA",
         "groot_n17": "GR00T N1.7", "groot_n16": "GR00T N1.6", "groot_n15": "GR00T N1.5"}
ORDER = ["pi0", "pi05", "smolvla", "groot_n17", "groot_n16", "groot_n15"]


def load(pattern: str) -> dict[str, list[dict]]:
    """model -> its rows, taking the NEWEST run per model.

    `pattern` is a COMMA-SEPARATED list, because GR00T's rows do not live in a consolidated
    directory. LABEL and ORDER below list all three GR00T versions, so including them was
    always the intent, but the old default glob was `results/*_E11_*_inputs` and GR00T's
    directories are named `results/<date>_E11a_groot_n17_hostseg`, which that pattern cannot
    match. The generator therefore reported "for N model(s)" with no GR00T row at all, and
    said nothing about it.

    GR00T legitimately has only E11a: E11c/d/e/f are built on the LeRobot phase loops and a
    transformers KV cache and GR00T has neither (scope statement in
    bench/queues/queue_e11.sh). Its rows populate the three per-segment quantities E11a
    produces and leave the later sections blank, which the GR00T scope note in the report
    states explicitly rather than leaving to inference.
    """
    by_model: dict[str, tuple[str, list[dict]]] = {}
    pats = [x.strip() for x in pattern.split(",") if x.strip()]
    # A consolidated `_E11_<m>_inputs` directory must win over an `_E11a_` one for the same model: plain sorting
    # put `..._E11a_groot_n17_hostseg` AFTER `..._E11_groot_n17_inputs` ('_' < 'a'), so the partial E11a file
    # would have replaced GR00T's consolidated one (2026-09-28).
    for d in sorted((x for pat in pats for x in glob.glob(pat)),
                    key=lambda x: (0 if "_E11a_" in x else 1, Path(x).name)):
        f = Path(d) / "model_inputs.csv"
        if not f.exists() or f.stat().st_size == 0:
            continue
        rows = list(csv.DictReader(f.open()))
        if not rows:
            continue
        m = rows[0].get("model", "?")
        # sorted() gives the newest date last, so a later run supersedes an earlier one
        by_model[m] = (d, rows)
    return {k: v[1] for k, v in by_model.items()}, {k: v[0] for k, v in by_model.items()}


def num(x):
    try:
        v = float(x)
        return v if v == v else None
    except (TypeError, ValueError):
        return None


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--glob",
                    default="results/*_E11_*_inputs,results/*_E11a_groot_*_hostseg",
                    help="comma-separated globs; GR00T has no consolidated dir")
    ap.add_argument("--out", default="reports/E11_models.md")
    args = ap.parse_args()

    data, dirs = load(args.glob)
    if not data:
        print(f"no consolidated E11 runs under {args.glob}")
        return 1
    models = [m for m in ORDER if m in data] + [m for m in data if m not in ORDER]

    L = ["# E11 — hybrid inputs, model by model", "",
         "**Generated by `bench/make_e11_models_report.py` from the committed "
         "`model_inputs.csv` files.** Nothing here is typed in.", "",
         "`model_inputs.csv` is the artefact the processing-in-memory model consumes "
         "directly. This puts the models side by side, because the differences between "
         "them decide whether a memory-side design generalises or was fitted to one "
         "architecture.", "",
         "**A blank cell means the model has no such segment**, not that it was measured "
         "at zero. SmolVLA has no AdaRMS gate; GR00T's attention is fused under SDPA and "
         "has no separable `softmax`; π0's conditioning tensor is `None` so it has no "
         "`adaln_cond`. Printing a zero for any of those would assert something false.",
         "",
         "**GR00T N1.7 has every E11 part since 2026-09-28** (T012 steps 2–7, `bench/groot_e11.py`): "
         "its hand-over object is the backbone's hidden states rather than a KV cache, and its 16 cross-attention "
         "blocks (of 32) re-project them at every denoising step — see `reports/E11_groot_n17_hybrid_inputs.md`. "
         "GR00T N1.5 / N1.6 still contribute E11a only.",
         ""]

    # ---- conditions --------------------------------------------------------------------
    L += ["## Conditions each run measured for itself", "",
          "| model | P (prefix tokens) | S (suffix tokens) | N | precision | run |",
          "|---|---:|---:|---:|---|---|"]
    for m in models:
        r = data[m][0]
        L.append(f"| {LABEL.get(m, m)} | {r.get('P', '') or '—'} | "
                 f"{r.get('S', '') or '—'} | {r.get('N', '')} | "
                 f"{r.get('precision', '')} | `{Path(dirs[m]).name}` |")
    L += ["",
          "π0's P = 816 is a property of `empty_cameras=1` and "
          "`tokenizer_max_length=48`. π0.5 has 0 and 200. Nothing here is copied between "
          "models.", ""]

    # ---- per-segment bytes, flops and eager time ----------------------------------------
    # §13.8's `quantity` is a closed table; the SEGMENT is in `key`. Grouping by a
    # quantity suffix found nothing at all, because no such quantity exists.
    for quantity, title, unit in (
            ("bytes_host_segment",
             "Bytes moved per segment (analytic, from the measured shapes)", "bytes"),
            ("flops_host_segment", "FLOPs per segment (analytic)", "flops"),
            ("t_host_segment", "Measured eager time per segment", "ms")):
        vals: dict[str, dict[str, float]] = defaultdict(dict)
        for m in models:
            for r in data[m]:
                if r.get("quantity") != quantity:
                    continue
                if quantity == "t_host_segment" and (
                        r.get("stat") != "median" or r.get("exec_style") != "eager"):
                    continue
                v = num(r.get("value"))
                if v is None:
                    continue
                seg = r.get("key") or "(no key)"
                # several layers/blocks per model: keep the largest, and say so
                vals[seg][m] = max(vals[seg].get(m, 0.0), v)
        if not vals:
            continue
        L += [f"## {title}", "",
              "| segment | " + " | ".join(LABEL.get(m, m) for m in models) + " |",
              "|---|" + "---:|" * len(models)]
        for seg in sorted(vals, key=lambda s: -max(vals[s].values())):
            cells = []
            for m in models:
                v = vals[seg].get(m)
                cells.append("—" if v is None else
                             (f"{v:,.0f}" if unit != "ms" else f"{v:.4f}"))
            L.append(f"| `{seg}` | " + " | ".join(cells) + " |")
        L += ["",
              "Where a model measured more than one layer or block, the **largest** is "
              "shown — the per-layer rows are in each run's own `model_inputs.csv` with "
              "a `layer=` or `block=` variant.", ""]

    # ---- coverage ------------------------------------------------------------------------
    L += ["## Coverage: which of §13.8's quantities each model actually has", "",
          "| model | distinct quantities | rows | not measured |", "|---|---:|---:|---|"]
    for m in models:
        qs = {r.get("quantity", "") for r in data[m]}
        L.append(f"| {LABEL.get(m, m)} | {len(qs)} | {len(data[m])} | "
                 f"see `{Path(dirs[m]).name}/summary.md` |")
    L += ["",
          "A quantity that could not be measured is **left out of `model_inputs.csv`** "
          "(protocol §13.8) and named in that run's `summary.md` with the command that "
          "failed. It is never written as a zero or an estimate.", ""]

    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(L) + "\n")
    print(f"wrote {args.out} ({len(L)} lines) for {len(models)} model(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
