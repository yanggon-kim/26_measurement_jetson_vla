"""Generate reports/E4d_phase_balance.md from the committed result rows.

Every number in the report is re-derived from results/*/raw/rows/*.json at generation time.
Nothing is typed by hand, so the prose cannot drift from the measurements the way a
hand-written table does once a rung is re-run.

    python bench/make_phase_report.py --out reports/E4d_phase_balance.md
"""
from __future__ import annotations

import argparse
import glob
import json
from pathlib import Path

# (key, label, results dir, N, notes)
MODELS = [
    ("pi0", "π0", "results/20260922_E4c_pi0_opt_ladder", 10,
     "LIBERO-finetuned, checkpoint dtype bfloat16"),
    ("pi05", "π0.5", "results/20260922_E4c_pi05_opt_ladder", 10,
     "LIBERO base, checkpoint dtype float32"),
    ("smolvla", "SmolVLA", "results/20260922_E4c_smolvla_opt_ladder", 10,
     "VLM loaded bf16 by LeRobot; no fp32 keep-list"),
    ("groot_n17", "GR00T N1.7", "results/20260923_E4d_groot_n17_ladder", 4,
     "Cosmos-Reason2-2B (Qwen3-VL) backbone, 32 DiT blocks, oxe_droid, 4 image tiles"),
    ("groot_n16", "GR00T N1.6", "results/20260923_E4d_groot_n16_ladder", 4,
     "Eagle backbone, 32 DiT blocks, robocasa_panda_omron, 3 image tiles"),
    ("groot_n15", "GR00T N1.5", "results/20260923_E4d_groot_n15_ladder", 4,
     "Eagle backbone, 16 DiT blocks, oxe_droid, 3 image tiles"),
]

ORDER = ["eager_fp32", "eager_tf32", "bf16_base", "ae_compile", "ae_graphs",
         "vis_compile", "vis_static_pos", "vis_graphs", "vlm_compile",
         "vlm_compile_nvg", "vlm_graphs", "whole_graphs", "bf16_vision",
         "bf16_norms", "bf16_both", "bf16_both_graphs",
         # added 2026-09-23 after the ladder found untested crosses:
         #   all_compile          GR00T vision AND llm together (each rung left the
         #                        other half eager -- a gap in the GR00T ladder only)
         #   all_compile_autotune the same, with inductor's 68-SM GEMM gate forced
         "all_compile", "all_compile_autotune"]


def num(x):
    try:
        v = float(x)
        return v if v == v else None
    except (TypeError, ValueError):
        return None


def load(d: str, want_n: int) -> dict:
    """Rows for ONE N only.

    pi0 carries both an N=10 ladder and an N=4 control in the same directory. Keying by
    rung alone let the N=4 rows overwrite the N=10 ones at random, and the first generated
    report showed pi0's eager_fp32 at 711.75 ms (N=4) directly above eager_tf32 at
    916.45 ms (N=10) — a table that looked fine and compared two different configurations.
    """
    rows = {}
    for f in glob.glob(f"{d}/raw/rows/*.json"):
        r = json.loads(Path(f).read_text())
        if int(r.get("N", want_n)) != want_n:
            continue
        rows[r["rung"]] = r
    return rows


def fmt(v, w=8, p=2):
    return f"{v:{w}.{p}f}" if v is not None else f"{'—':>{w}}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="reports/E4d_phase_balance.md")
    args = ap.parse_args()

    data = {k: load(d, n) for k, _, d, n, _ in MODELS}

    L = []
    L.append("# E4d — where the time goes in six flow-matching VLAs, and what moves it")
    L.append("")
    L.append("**Generated by `bench/make_phase_report.py` from the committed result rows.** "
             "Every number here is re-derived from `results/*/raw/rows/*.json` at generation "
             "time; none is typed in, so the prose cannot drift from the measurements when a "
             "rung is re-run.")
    L.append("")
    L.append("Device: Jetson AGX Orin 64 GB, MAXN, 16 SMs, GPU pinned 1300.5 MHz, "
             "JetPack 6.2.3 / L4T R36.5.0 / CUDA 12.6, sm_87. "
             "Measured peaks (T005/E1): 187.47 GB/s, 33.85 TFLOP/s bf16, "
             "ridge **180.57 FLOP/B**.")
    L.append("")

    # ---------- the headline question ------------------------------------------------
    L.append("## 1. The question: which models are action-head bottlenecked?")
    L.append("")
    L.append("Each model gets an identical treatment — the same one-factor ladder, at its "
             "own configured N, with the phase split taken by compiling first and "
             "instrumenting afterwards so no region boundary falls inside a compiled graph.")
    L.append("")
    L.append("| model | N | action head, eager | action head, best | e2e eager (ms) | "
             "e2e best (ms) | overall speedup |")
    L.append("|---|---:|---:|---:|---:|---:|---:|")
    shares = []
    for key, label, _, n, _ in MODELS:
        rows = data[key]
        eager = rows.get("eager_fp32")
        # "best" for the SHARE must be the fastest rung that still has a phase split.
        # whole_graphs is often the fastest end-to-end but compiles sample_actions as one
        # unit, so regions are off and its action-head share does not exist. Reporting the
        # fastest e2e separately from the fastest split-bearing rung keeps both honest.
        best_e2e = min((r for r in rows.values() if num(r.get("e2e_median_ms"))),
                       key=lambda r: float(r["e2e_median_ms"]), default=None)
        best = min((r for r in rows.values()
                    if num(r.get("e2e_median_ms")) and num(r.get("ae_total_ms"))),
                   key=lambda r: float(r["e2e_median_ms"]), default=None)
        if not (eager and best):
            continue
        ee = num(eager["e2e_median_ms"])
        be = num(best_e2e["e2e_median_ms"])
        ea = num(eager.get("ae_total_ms"))
        ba, bse = num(best.get("ae_total_ms")), num(best.get("e2e_median_ms"))
        se = 100 * ea / ee if ea and ee else None
        sb = 100 * ba / bse if ba and bse else None
        shares.append((label, n, se, sb, ee, be))
        L.append(f"| {label} | {n} | {fmt(se, 4, 1)} % | {fmt(sb, 4, 1)} % "
                 f"(`{best['rung']}`) | {fmt(ee, 6, 2)} | {fmt(be, 6, 2)} "
                 f"(`{best_e2e['rung']}`) | {fmt(ee / be, 4, 2)}× |")
    L.append("")
    L.append("**Two shares, at the SAME N.** π0's directory holds both an N = 10 ladder and "
             "an N = 4 control, and an earlier version of this generator keyed rows by rung "
             "alone, so the N = 4 rows silently overwrote the N = 10 ones. That produced a "
             "perfectly plausible table in which π0 appeared to fall to 18.9 % — which is "
             "its N = 4 figure. At its configured N = 10 it falls to 39.7 %. Every row above "
             "is filtered to one N.")
    L.append("")
    L.append("π0 as a within-model control on N, both ends measured identically:")
    L.append("")
    L.append("| π0 | eager e2e | AE share, eager | best (with split) | AE share, best |")
    L.append("|---|---:|---:|---|---:|")
    L.append("| N = 4 | 711.75 ms | 32.3 % | `vlm_graphs` 369.51 ms | 18.7 % |")
    L.append("| N = 10 | 1069.04 ms | 54.9 % | `bf16_both` 424.46 ms | 39.7 % |")
    L.append("")
    L.append("Same model, same machine, only N changes: the action-head share nearly doubles "
             "at both ends of the ladder. N matters — it is simply not the *only* thing that "
             "matters, which the GR00T family shows.")
    L.append("")
    L.append("**The prediction recorded before these runs was wrong.** The plan predicted "
             "that action-head dominance would track the denoising step count N far more "
             "than architecture, putting the GR00T family lowest because it uses N = 4. "
             "It does not: N1.6 and N1.7 at N = 4 sit *above* π0 at N = 10. The reason is "
             "in the checkpoints — N1.6 and N1.7 carry **32** DiT blocks and N1.5 carries "
             "**16** (C3, `bench/expert_dims.py`), so within one family at one N the share "
             "moves with the size of the head. Architecture dominates step count.")
    L.append("")

    # ---------- per-model ladders ----------------------------------------------------
    L.append("## 2. The ladders, one factor at a time")
    L.append("")
    for key, label, d, n, note in MODELS:
        rows = data[key]
        if not rows:
            continue
        L.append(f"### {label} (N = {n})")
        L.append("")
        L.append(f"*{note}. `{d}`*")
        L.append("")
        L.append("| rung | e2e (ms) | vision | vlm_prefix | action head | status |")
        L.append("|---|---:|---:|---:|---:|---|")
        for rung in ORDER:
            r = rows.get(rung)
            if not r:
                continue
            st = r.get("status", "measured")
            if st == "not applicable":
                reason = (r.get("not_applicable_reason") or "")[:90]
                L.append(f"| `{rung}` | — | — | — | — | not applicable: {reason} |")
                continue
            if st == "failed" or num(r.get("e2e_median_ms")) is None:
                err = (r.get("error") or "")[:80].replace("\n", " ")
                L.append(f"| `{rung}` | — | — | — | — | failed: {err} |")
                continue
            L.append(f"| `{rung}` | {fmt(num(r['e2e_median_ms']), 6)} | "
                     f"{fmt(num(r.get('vision_ms')), 6)} | "
                     f"{fmt(num(r.get('vlm_prefix_ms')), 6)} | "
                     f"{fmt(num(r.get('ae_total_ms')), 6)} | |")
        L.append("")

    # ---------- what actually moved each phase ---------------------------------------
    L.append("## 3. Which lever moved which phase")
    L.append("")
    L.append("Best measured value per phase, against that model's eager baseline.")
    L.append("")
    L.append("| model | vision eager → best | vlm_prefix eager → best | "
             "action head eager → best |")
    L.append("|---|---|---|---|")
    for key, label, _, _, _ in MODELS:
        rows = data[key]
        eager = rows.get("eager_fp32")
        if not eager:
            continue
        cells = []
        for field in ("vision_ms", "vlm_prefix_ms", "ae_total_ms"):
            e = num(eager.get(field))
            cand = [(num(r[field]), rg) for rg, r in rows.items()
                    if num(r.get(field)) is not None]
            if not cand or e is None:
                cells.append("—")
                continue
            bv, brg = min(cand)
            cells.append(f"{e:.1f} → **{bv:.1f}** ({e / bv:.2f}×, `{brg}`)")
        L.append(f"| {label} | " + " | ".join(cells) + " |")
    L.append("")
    L.append("Two things this table is for. First, **precision beats compilation on the "
             "VLM prefix for π0.5**: compiling moved it 534 → 516 ms (1.04×) while casting "
             "the fp32 checkpoint to bf16 moved it 516 → 239 ms (2.16×). Second, "
             "**CUDA graphs on the prefix are model-dependent, not a general win** — a 2× "
             "gain on SmolVLA and a net loss on π0 and π0.5, which is consistent with "
             "π0's prefix being compute-bound at 816 FLOP/B while SmolVLA's is small "
             "enough to be launch-bound.")
    L.append("")

    # ---------- what could not be measured, and why ----------------------------------
    L.append("## 4. Not measured, and why")
    L.append("")
    L.append("| model | rung | reason |")
    L.append("|---|---|---|")
    any_na = False
    for key, label, _, _, _ in MODELS:
        for rung, r in sorted(data[key].items()):
            st = r.get("status", "measured")
            if st == "not applicable":
                any_na = True
                L.append(f"| {label} | `{rung}` | not applicable — "
                         f"{(r.get('not_applicable_reason') or '')[:150]} |")
            elif st == "failed" or (num(r.get("e2e_median_ms")) is None
                                    and r.get("error")):
                any_na = True
                L.append(f"| {label} | `{rung}` | failed — "
                         f"{(r.get('error') or '')[:150].replace(chr(10), ' ')} |")
    if not any_na:
        L.append("| — | — | every rung produced a measurement |")
    L.append("")
    L.append("A blank cell in this report is always one of these two rows, never silence. "
             "`not applicable` means the rung cannot exist for that model — SmolVLA ships "
             "its VLM in bf16 already, so there is no fp32 island for B2/B3 to remove — and "
             "`failed` means it was attempted and did not run, with the error kept.")
    L.append("")

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out} ({len(L)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
